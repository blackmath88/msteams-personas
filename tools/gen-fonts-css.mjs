#!/usr/bin/env node
// Writes assets/fonts.css from the WOFF2 files in assets/fonts/.
//
// The fonts are embedded as data URIs on purpose:
//   - index.html keeps working when opened from file:// and offline;
//   - the PNG export serialises all CSS into an SVG image (src/export.js), and an SVG image
//     cannot load external files, so a url(…woff2) reference would silently fall back to
//     whatever fonts the machine has.
// Run again after changing a font file: node tools/gen-fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FACES = [
  ['Selawik', 400, 'selawik-regular.woff2'],
  ['Selawik', 600, 'selawik-semibold.woff2'],
  ['Selawik', 700, 'selawik-bold.woff2'],
  /* ← ↑ → ↓ ✓ only: Selawik has no arrows or tick, and a system fallback would differ per machine. */
  ['MTP Symbols', 400, 'symbols-dejavu-subset.woff2', 'U+2190-2193,U+2713']
];
const face = ([family, weight, file, range]) =>
  `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;` +
  `src:url(data:font/woff2;base64,${readFileSync(join(ROOT, 'assets/fonts', file)).toString('base64')}) format("woff2")` +
  (range ? `;unicode-range:${range}` : '') + '}';

const css = `/* Generated by tools/gen-fonts-css.mjs – do not edit. Licences: THIRD-PARTY-NOTICES.md.
 * Selawik 1.01 (SIL OFL 1.1, Microsoft) is metric-compatible with Segoe UI. Bundling it makes
 * text wrapping, fit checks and exported PNGs the same on every machine. */
${FACES.map(face).join('\n')}
:root{--mtp-font:"Selawik","MTP Symbols","Segoe UI",system-ui,-apple-system,"Noto Sans","Helvetica Neue",Arial,sans-serif}
`;
writeFileSync(join(ROOT, 'assets/fonts.css'), css);
console.error(`assets/fonts.css written (${css.length} bytes, ${FACES.length} faces)`);
